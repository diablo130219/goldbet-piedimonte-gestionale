-- Neon PostgreSQL schema for GoldBet Piedimonte. Idempotent / no destructive migrations.
CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username TEXT NOT NULL UNIQUE, full_name TEXT NOT NULL, password_hash TEXT NOT NULL,
 role TEXT NOT NULL CHECK (role IN ('admin','operator')),
 active INTEGER NOT NULL DEFAULT 1, created_at TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_users_lower_username ON users(LOWER(username));
CREATE TABLE IF NOT EXISTS sessions (
 token_hash TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id), expires_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS clients (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 first_name TEXT NOT NULL, last_name TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS shifts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cash_number INTEGER NOT NULL CHECK(cash_number IN (1,2)),
 user_id BIGINT NOT NULL REFERENCES users(id), opening_date TEXT NOT NULL,
 opened_at TEXT NOT NULL, initial_cents BIGINT NOT NULL,
 green_cents BIGINT NOT NULL DEFAULT 0, red_cents BIGINT NOT NULL DEFAULT 0,
 physical_cents BIGINT, expected_cents BIGINT, difference_cents BIGINT,
 close_note TEXT NOT NULL DEFAULT '', closed_at TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_active_shift_per_cash
 ON shifts(cash_number) WHERE closed_at IS NULL;
CREATE TABLE IF NOT EXISTS movements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 client_id BIGINT NOT NULL REFERENCES clients(id), shift_id BIGINT NOT NULL REFERENCES shifts(id),
 user_id BIGINT NOT NULL REFERENCES users(id),
 kind TEXT NOT NULL CHECK(kind IN ('debit','credit')),
 amount_cents BIGINT NOT NULL CHECK(amount_cents>0),
 note TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL,
 voided_at TEXT, voided_by BIGINT REFERENCES users(id), void_reason TEXT
);
CREATE INDEX IF NOT EXISTS ix_movements_client ON movements(client_id,id);
CREATE INDEX IF NOT EXISTS ix_movements_shift ON movements(shift_id,id);
CREATE TABLE IF NOT EXISTS cash_adjustments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 shift_id BIGINT NOT NULL REFERENCES shifts(id),
 user_id BIGINT NOT NULL REFERENCES users(id),
 label TEXT NOT NULL,
 direction TEXT NOT NULL CHECK(direction IN ('in','out')),
 amount_cents BIGINT NOT NULL CHECK(amount_cents>0),
 note TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL,
 voided_at TEXT, voided_by BIGINT REFERENCES users(id), void_reason TEXT
);
CREATE INDEX IF NOT EXISTS ix_cash_adjustments_shift ON cash_adjustments(shift_id,id);
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 client_id BIGINT NOT NULL REFERENCES clients(id),
 kind TEXT NOT NULL CHECK(kind IN ('overdue','paid')),
 message TEXT NOT NULL, amount_cents BIGINT NOT NULL,
 created_at TEXT NOT NULL, resolved_at TEXT
);
CREATE INDEX IF NOT EXISTS ix_notifications_client ON notifications(client_id,kind,resolved_at);
CREATE TABLE IF NOT EXISTS notification_reads (
 notification_id BIGINT NOT NULL REFERENCES notifications(id),
 user_id BIGINT NOT NULL REFERENCES users(id), read_at TEXT NOT NULL,
 PRIMARY KEY(notification_id,user_id)
);
CREATE TABLE IF NOT EXISTS audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id BIGINT REFERENCES users(id), action TEXT NOT NULL,
 entity TEXT NOT NULL, entity_id BIGINT, details TEXT NOT NULL DEFAULT '{}',
 created_at TEXT NOT NULL
);
-- Blue-only migration. NULL means a legacy shift: show its original green-red balance.
-- Existing breakdown remains untouched for historical integrity.
ALTER TABLE shifts ADD COLUMN IF NOT EXISTS manual_blue_cents BIGINT;

-- Logos are stored in PostgreSQL because Render Free has no persistent disk.
CREATE TABLE IF NOT EXISTS brand_assets (
 id INTEGER PRIMARY KEY CHECK (id=1),
 mime TEXT NOT NULL, extension TEXT NOT NULL,
 content BYTEA NOT NULL, updated_at TEXT NOT NULL
);